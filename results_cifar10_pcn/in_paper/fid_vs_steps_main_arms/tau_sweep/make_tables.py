#!/usr/bin/env python3
"""Build tables_tau_sweep_not_in_paper.tex: the paired tau_s sweep of the two PCN phase-2 arms.

Standalone: reads only the fidlog_*.log files next to it, writes the .tex next to itself.
    uv run python3 make_tables.py

NOTE the absolute level is 2048-sample bias, not an FID: the same checkpoints score 3.6351 (IFT) /
3.6401 (EP) under the 50k protocol. Only the LOCATION of the minimum is meaningful, because the tau
points are consecutive segments of the same trajectories.
"""
import glob, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "tables_tau_sweep_not_in_paper.tex")


def table_tau():
    arms = {}
    for f in sorted(glob.glob(os.path.join(HERE, "fidlog_*.log"))):
        txt = open(f, errors="replace").read()
        pts = {float(t): float(v) for t, v in re.findall(r"FID at t=([0-9.]+) => ([0-9.]+)", txt)}
        if not pts:
            continue
        arm = "IFT" if "ift_" in os.path.basename(f) else "EP"
        n = re.search(r"fake: (\d+)", txt)
        if arm not in arms or len(pts) > len(arms[arm][0]):
            arms[arm] = (pts, int(n.group(1)) if n else 0)
    taus = sorted({t for pts, _ in arms.values() for t in pts})
    L = [
        "% Generated by make_tables.py from FIDLOG_*.INFO.",
        "% EMA, seed 1, PCN weights loaded into the feedforward twin, tau points integrated as",
        "% CONSECUTIVE SEGMENTS of the same trajectories (so the row is paired across tau).",
        "% NOT FIDs: the level is small-sample bias. 50k protocol gives 3.6351 (IFT) / 3.6401 (EP).",
        r"\begin{tabular}{l" + "c" * len(taus) + "}", r"\toprule",
        r"$\tau_s$ & " + " & ".join(f"{t:g}" for t in taus) + r" \\", r"\midrule",
    ]
    for arm in ("IFT", "EP"):
        if arm not in arms:
            continue
        pts, nfake = arms[arm]
        best = min(pts, key=pts.get)
        cells = [(r"\textbf{%.4f}" % pts[t]) if t == best else f"{pts[t]:.4f}"
                 if t in pts else "--" for t in taus]
        L.append(f"{arm} ({nfake} samples) & " + " & ".join(cells) + r" \\")
    L += [r"\bottomrule", r"\end{tabular}"]
    for arm in ("IFT", "EP"):
        if arm in arms:
            L.append(f"% {arm}: minimum at tau = {min(arms[arm][0], key=arms[arm][0].get):g}")
    return "\n".join(L) + "\n"


open(OUT, "w").write(table_tau())
print("wrote", OUT)
